const { chromium } = require('playwright');
const fs = require('fs');
const BASE = process.env.NEBULA_BASE || 'http://127.0.0.1:8000';
(async () => {
  const browser = await chromium.launch({ headless:true, args:['--no-sandbox'] });
  const page = await browser.newPage({ viewport:{width:1440,height:1000}, acceptDownloads:true });
  const errors=[]; page.on('pageerror', e=>errors.push(String(e)));
  const failed=[]; page.on('response', r=>{ if(r.status()>=500) failed.push(`${r.status()} ${r.url()}`); });
  await page.goto(BASE, { waitUntil:'domcontentloaded' });
  await page.waitForSelector('.login-card');
  await page.locator('input[type=email]').fill(process.env.ADMIN_EMAIL);
  await page.locator('input[type=password]').fill(process.env.ADMIN_PASSWORD);
  await page.locator('button[type=submit]').click();
  await page.waitForSelector('.dashboard');
  await page.locator('.nb-card').first().click();
  await page.waitForSelector('.editor-shell');
  const downloadPromise = page.waitForEvent('download', { timeout: 30000 });
  await page.getByRole('button', { name: /^Export/ }).click();
  const download = await downloadPromise;
  const out = '/tmp/export-demo.ipynb';
  await download.saveAs(out);
  const doc = JSON.parse(fs.readFileSync(out,'utf8'));
  console.log('suggested filename', download.suggestedFilename(), 'nbformat', doc.nbformat, 'cells', doc.cells.length, 'bytes', fs.statSync(out).size);
  console.log('pageerrors', errors, '5xx', failed);
  await page.screenshot({ path:'../screenshots/16-export-fixed.png', fullPage:true });
  const ok = doc.nbformat === 4 && errors.length === 0 && failed.length === 0;
  await browser.close();
  console.log(ok ? 'PASS export' : 'FAIL export');
  process.exit(ok?0:1);
})();
