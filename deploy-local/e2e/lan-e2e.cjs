const { chromium } = require('playwright');
const BASE = process.env.NEBULA_LAN_BASE || 'http://127.0.0.1:8000';
const results=[]; const check=(n,c,d='')=>{results.push(c);console.log(`${c?'  PASS':'  FAIL'}  ${n}${c?'':' '+d}`)};
(async () => {
  const browser = await chromium.launch({ headless:true, args:['--no-sandbox'] });
  const page = await browser.newPage({ viewport:{width:1440,height:1000} });
  const errors=[]; page.on('pageerror', e=>errors.push(String(e)));
  page.on('dialog', d=>d.accept());
  await page.goto(BASE, { waitUntil:'domcontentloaded' });
  const env = await page.evaluate(() => ({secure: window.isSecureContext, uuid: typeof crypto.randomUUID, gRV: typeof crypto.getRandomValues}));
  console.log('browser env', JSON.stringify(env));
  check('plain-HTTP LAN origin is insecure + randomUUID unavailable (repro condition)', env.secure===false && env.uuid==='undefined' && env.gRV==='function');
  await page.waitForSelector('.login-card');
  await page.locator('input[type=email]').fill(process.env.ADMIN_EMAIL);
  await page.locator('input[type=password]').fill(process.env.ADMIN_PASSWORD);
  await page.locator('button[type=submit]').click();
  await page.waitForSelector('.dashboard');
  await page.getByRole('button', { name: /New notebook/i }).first().click();
  await page.locator('.modal input').first().fill('LAN fix validation');
  await page.getByRole('button', { name: /Create notebook/i }).click();
  await page.waitForSelector('.editor-shell');
  const connect = page.locator('.runtime-controls button.primary');
  await connect.waitFor({ state:'visible', timeout:30000 });
  await page.waitForFunction(() => { const b=document.querySelector('.runtime-controls button.primary'); return b && !b.disabled; }, { timeout:60000 });
  await connect.click();
  await page.waitForFunction(() => document.querySelector('.runtime-mode')?.textContent.includes('Kernel ready'), { timeout:90000 });
  check('connect kernel over plain HTTP LAN origin', true);
  await page.locator('.cell .run-cell').first().click();
  await page.waitForFunction(() => document.body.innerText.includes('Hello, Nebula Notebook!'), { timeout:45000 });
  check('run existing cell produces output over LAN origin', true);
  const before = await page.locator('.cell').count();
  await page.getByRole('button', { name: /^Code/ }).first().click();
  await page.waitForFunction(n => document.querySelectorAll('.cell').length === n+1, before, { timeout:10000 });
  check('new code cell can be added over LAN origin', true);
  await page.locator('.cm-content').last().click();
  await page.keyboard.type('sum(range(10))');
  await page.locator('.cell .run-cell').last().click();
  await page.waitForFunction(() => [...document.querySelectorAll('.output-text')].some(n => n.textContent.trim()==='45'), { timeout:45000 });
  check('new cell executes over LAN origin', true);
  await page.getByRole('button', { name: /^Run all/ }).click();
  await page.waitForTimeout(3000);
  check('Run all does not crash', errors.length===0, errors.join(' | '));
  await page.screenshot({ path:'../screenshots/13-lan-fixed.png', fullPage:true });
  await page.getByRole('button', { name: /Delete notebook/i }).click();
  await page.waitForSelector('.dashboard', { timeout:20000 });
  check('no uncaught page errors for whole LAN flow', errors.length===0, errors.join(' | '));
  await browser.close();
  const failed=results.filter(x=>!x).length; console.log(`\nSUMMARY ${results.length-failed}/${results.length} passed`);
  process.exit(failed?1:0);
})();
