const { chromium } = require('playwright');
const BASE = process.env.NEBULA_LAN_BASE || 'http://127.0.0.1:8000';
(async () => {
  const browser = await chromium.launch({ headless: true, args:['--no-sandbox'] });
  const page = await browser.newPage({ viewport:{width:1440,height:1000} });
  const errors=[], consoleErr=[];
  page.on('pageerror', e=>errors.push(String(e)));
  page.on('console', m=>{ if(m.type()==='error') consoleErr.push(m.text()); });
  await page.goto(BASE, { waitUntil:'domcontentloaded' });
  console.log('env', await page.evaluate(() => ({secure: window.isSecureContext, uuid: typeof crypto.randomUUID, gRV: typeof crypto.getRandomValues})));
  await page.waitForSelector('.login-card');
  await page.locator('input[type=email]').fill(process.env.ADMIN_EMAIL);
  await page.locator('input[type=password]').fill(process.env.ADMIN_PASSWORD);
  await page.locator('button[type=submit]').click();
  await page.waitForSelector('.dashboard');
  await page.locator('.nb-card').first().click();
  await page.waitForSelector('.editor-shell');
  const connectBtn = page.locator('.runtime-controls button.primary');
  await connectBtn.waitFor({ state:'visible', timeout:30000 });
  await page.waitForFunction(() => {
    const b = document.querySelector('.runtime-controls button.primary');
    return b && !b.disabled;
  }, { timeout:60000 });
  await connectBtn.click();
  await page.waitForFunction(() => document.querySelector('.runtime-mode')?.textContent.includes('Kernel ready'), { timeout:90000 }).catch(e=>console.log('kernel wait failed', e.message));
  console.log('after connect errors', errors);
  await page.locator('.cell .run-cell').first().click();
  await page.waitForTimeout(4000);
  console.log('output text', (await page.locator('.output-text').allTextContents()).slice(0,3));
  console.log('page errors after run', errors);
  console.log('body has error banner', await page.locator('.alert').allTextContents());
  await page.getByRole('button', { name: /^Code/ }).first().click();
  await page.waitForTimeout(1500);
  console.log('cells after add', await page.locator('.cell').count());
  console.log('page errors after add', errors);
  console.log('console errors', consoleErr.slice(0,5));
  await page.screenshot({ path:'../screenshots/12-lan-repro.png', fullPage:true });
  await browser.close();
})();
