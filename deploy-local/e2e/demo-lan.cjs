const { chromium } = require('playwright');
const BASE = process.env.NEBULA_LAN_BASE || 'http://127.0.0.1:8000';
(async () => {
  const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[]; page.on('pageerror',e=>errors.push(String(e)));
  await page.goto(BASE,{waitUntil:'domcontentloaded'});
  await page.waitForSelector('.login-card');
  await page.locator('input[type=email]').fill(process.env.ADMIN_EMAIL);
  await page.locator('input[type=password]').fill(process.env.ADMIN_PASSWORD);
  await page.locator('button[type=submit]').click();
  await page.waitForSelector('.dashboard');
  await page.locator('.nb-card').first().click();
  await page.waitForSelector('.editor-shell');
  await page.waitForFunction(() => document.querySelector('.runtime-mode')?.textContent.includes('Kernel ready'), {timeout:30000});
  const before=await page.locator('.cell').count();
  await page.locator('.cell .run-cell').first().click();
  await page.waitForFunction(() => [...document.querySelectorAll('.output-text')].some(n=>n.textContent.includes('Python:')), {timeout:45000});
  console.log('PASS demo run output');
  await page.getByRole('button',{name:/^Code/}).first().click();
  await page.waitForFunction(n=>document.querySelectorAll('.cell').length===n+1,before,{timeout:10000});
  console.log('PASS demo new cell');
  await page.getByRole('button',{name:/^Run all/}).click();
  await page.waitForSelector('.output-image img',{timeout:45000});
  console.log('PASS demo run all plot; pageerrors',errors.length);
  await page.screenshot({path:'../screenshots/14-demo-lan-fixed.png',fullPage:true});
  await browser.close();
  process.exit(errors.length?1:0);
})();
